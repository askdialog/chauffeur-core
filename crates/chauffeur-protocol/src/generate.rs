//! What `protocol-ts` cannot take from ts-rs alone: the method → `[params, result]` maps of the
//! method enums and the error codes, written to `protocol-ts/src/generated/methods.ts` by
//! `scripts/gen-protocol.sh` (the `gen` binary). A test fails when that file is not up to date.

use std::collections::BTreeMap;
use std::fmt::Write;

use ts_rs::{Config, Dependency, TS, TypeVisitor};

use crate::client::{ClientMethod, DaemonNotificationMethod, MobileHostMethod};
use crate::methods::Method;
use crate::peer::PeerMethod;
use crate::rpc::codes;
use crate::sidecar::{SidecarMethod, SidecarToDaemonMethod};

/// Where the file lives, from the workspace's root.
pub const METHODS_TS: &str = "protocol-ts/src/generated/methods.ts";

/// The content of [`METHODS_TS`].
pub fn methods_ts() -> String {
    let cfg = Config::new();
    let mut body = String::new();
    let mut imports = Imports {
        cfg: &cfg,
        found: BTreeMap::new(),
    };
    writeln!(
        body,
        "export const PROTOCOL_VERSION = {};\nexport const MIN_PROTOCOL_VERSION = {};\nexport const PEER_PROTOCOL_VERSION = {};",
        crate::PROTOCOL_VERSION,
        crate::MIN_PROTOCOL_VERSION,
        crate::peer::PEER_PROTOCOL_VERSION
    )
    .expect("a String takes any write");
    requests::<ClientMethod>(
        &mut body,
        &mut imports,
        "ClientMethods",
        "Client → daemon methods (`ClientCall`): `[params, result]`.",
    );
    requests::<crate::extension_host::ExtensionHostMethod>(
        &mut body,
        &mut imports,
        "ExtensionHostMethods",
        "Official engine → Core callbacks on private process pipes (`ExtensionHostCall`).",
    );
    notifications::<crate::extension_host::ExtensionEngineNotificationMethod>(
        &mut body,
        &mut imports,
        "ExtensionEngineNotifications",
        "Core → official engine notifications on private process pipes.",
    );
    notifications::<DaemonNotificationMethod>(
        &mut body,
        &mut imports,
        "DaemonNotifications",
        "Daemon → client notifications (`DaemonNotification`).",
    );
    requests::<PeerMethod>(
        &mut body,
        &mut imports,
        "PeerMethods",
        "Daemon → daemon methods on its socket's `/peer` path (`PeerCall`): `[params, result]`.",
    );
    requests::<MobileHostMethod>(
        &mut body,
        &mut imports,
        "MobileHostMethods",
        "Phone → mobile host methods it answers itself (`MobileHostCall`): `[params, result]`.",
    );
    requests::<SidecarMethod>(
        &mut body,
        &mut imports,
        "SidecarMethods",
        "Daemon → sidecar methods (`SidecarCall`): `[params, result]`.",
    );
    requests::<SidecarToDaemonMethod>(
        &mut body,
        &mut imports,
        "DaemonHookMethods",
        "Sidecar → daemon requests (`SidecarToDaemon`): `[params, result]`.",
    );
    notifications::<SidecarToDaemonMethod>(
        &mut body,
        &mut imports,
        "SidecarNotifications",
        "Sidecar → daemon notifications (`SidecarToDaemon`).",
    );
    writeln!(
        body,
        "\n/** Every method name of `ClientCall`. */\nexport const METHOD_NAMES = {} as const;",
        names::<ClientMethod>(|_| true)
    )
    .expect("a String takes any write");
    writeln!(
        body,
        "\n/** Every method name of `PeerCall`, which travel on the socket's `/peer` path. */\nexport const PEER_METHOD_NAMES = {} as const;",
        names::<PeerMethod>(|_| true)
    )
    .expect("a String takes any write");
    writeln!(
        body,
        "\n/** The `ClientCall` methods the phone may call through the mobile host (`#[access(.., phone)]`). */\nexport const PHONE_METHODS = {} as const;",
        names::<ClientMethod>(ClientMethod::phone)
    )
    .expect("a String takes any write");
    writeln!(
        body,
        "\n/** The methods the mobile host answers itself (`MobileHostCall`). */\nexport const MOBILE_HOST_METHODS = {} as const;",
        names::<MobileHostMethod>(|_| true)
    )
    .expect("a String takes any write");
    body.push_str("\n/** JSON-RPC error codes (`chauffeur_protocol::rpc::codes`). */\n");
    body.push_str("export const ErrorCode = {\n");
    for (name, code) in codes::ALL {
        writeln!(body, "  {name}: {code},").expect("a String takes any write");
    }
    body.push_str("} as const;\n");

    let mut out = String::from("// Generated by scripts/gen-protocol.sh. Do not edit.\n");
    for (name, path) in &imports.found {
        writeln!(out, "import type {{ {name} }} from \"./{path}\";")
            .expect("a String takes any write");
    }
    out.push('\n');
    out.push_str(&body);
    out
}

fn requests<M: Method>(out: &mut String, imports: &mut Imports, name: &str, doc: &str) {
    writeln!(out, "\n/** {doc} */\nexport type {name} = {{").expect("a String takes any write");
    for method in M::ALL {
        if let Some(result) = method.result(imports.cfg) {
            method.visit_types(imports);
            let params = method.params(imports.cfg);
            writeln!(out, "  \"{}\": [{params}, {result}];", method.name())
                .expect("a String takes any write");
        }
    }
    out.push_str("};\n");
}

fn notifications<M: Method>(out: &mut String, imports: &mut Imports, name: &str, doc: &str) {
    writeln!(out, "\n/** {doc} */\nexport type {name} = {{").expect("a String takes any write");
    for method in M::ALL {
        if method.result(imports.cfg).is_none() {
            method.visit_types(imports);
            let params = method.params(imports.cfg);
            writeln!(out, "  \"{}\": {params};", method.name()).expect("a String takes any write");
        }
    }
    out.push_str("};\n");
}

/// The names of `M`'s methods that `keep`, as a TypeScript array.
fn names<M: Method>(keep: impl Fn(M) -> bool) -> String {
    let names: Vec<String> = M::ALL
        .iter()
        .filter(|method| keep(**method))
        .map(|method| format!("\n  \"{}\",", method.name()))
        .collect();
    format!("[{}\n]", names.concat())
}

/// The exported types a map names, by TypeScript name: their file, without its extension.
struct Imports<'a> {
    cfg: &'a Config,
    found: BTreeMap<String, String>,
}

impl TypeVisitor for Imports<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        match Dependency::from_ty::<T>(self.cfg) {
            Some(dependency) => {
                let path = dependency.output_path.with_extension("");
                self.found
                    .insert(dependency.ts_name, path.to_string_lossy().into_owned());
            }
            // A wrapper (`Box<T>`, `Option<T>`) or a primitive: what it holds, if anything.
            None => T::visit_generics(self),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_generated_method_maps_are_up_to_date() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join(METHODS_TS);
        let on_disk = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            on_disk == methods_ts(),
            "{METHODS_TS} is out of date with the method enums: run scripts/gen-protocol.sh"
        );
    }
}
