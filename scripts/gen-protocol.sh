#!/usr/bin/env bash
# Regenerates the TypeScript protocol from the Rust types (crates/chauffeur-protocol): ts-rs writes
# a file per type when the crate's tests run, the `gen` binary the method maps and error codes.
set -euo pipefail
cd "$(dirname "$0")/.."
rm -rf protocol-ts/src/generated
cargo run -q -p chauffeur-protocol --bin gen
cargo test -q -p chauffeur-protocol >/dev/null
{
  echo "// Generated by scripts/gen-protocol.sh. Do not edit."
  for f in protocol-ts/src/generated/*.ts; do
    name=$(basename "$f" .ts)
    [ "$name" = index ] || [ "$name" = methods ] && continue
    echo "export type { ${name} } from \"./${name}\";"
  done
  echo "export type { JsonValue } from \"./serde_json/JsonValue\";"
  echo "export * from \"./methods\";"
} > protocol-ts/src/generated/index.ts
echo "protocol-ts regenerated: $(ls protocol-ts/src/generated | wc -l | tr -d ' ') files"
