import { describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { SessionMessage } from "@anthropic-ai/claude-agent-sdk";
import { claudeSessionMessages, sessionEvents } from "../src/agents/claude/session-messages.ts";
import type { TranscriptReader } from "../src/agents/claude/subagents.ts";

const SESSION = "db8d5562-05cf-4bce-9d6c-35b6eefb5d1a";

/** A reader that knows no transcript. */
const nothing: TranscriptReader = {
  messages: async () => [],
  list: async () => [],
  session: async () => [],
};

describe("an imported session's conversation", () => {
  const at = (minute: number) => `2026-10-01T10:${String(minute).padStart(2, "0")}:00.000Z`;
  const message = (type: "user" | "assistant", minute: number, body: unknown, extra: Record<string, unknown> = {}) =>
    ({ type, uuid: `u${minute}`, session_id: SESSION, message: body, parent_tool_use_id: null, parent_agent_id: null, timestamp: at(minute), ...extra }) as SessionMessage;

  test("shows the user's prompts as typed, without what Claude Code adds, the agent's text, tool calls and results, each at its message's time", () => {
    const events = sessionEvents([
      message("user", 0, { role: "user", content: "This session is being continued…" }, { isCompactSummary: true }),
      message("user", 1, { role: "user", content: "Why does the build fail?" }),
      message("user", 2, { role: "user", content: "Caveat: the messages below were generated by the user while running local commands." }, { is_meta: true }),
      message("assistant", 3, { id: "msg_1", role: "assistant", content: [
        { type: "text", text: "Let me look." },
        { type: "tool_use", id: "toolu_1", name: "Bash", input: { command: "make" } },
      ] }),
      message("user", 4, { role: "user", content: [{ type: "tool_result", tool_use_id: "toolu_1", content: "error: x" }] }),
      message("user", 5, { role: "user", content: "<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>the diff</command-args>" }),
      message("user", 6, { role: "user", content: "<local-command-stdout>done</local-command-stdout>" }),
      message("user", 7, { role: "user", content: [{ type: "text", text: "[Request interrupted by user for tool use]" }] }),
      message("user", 8, { role: "user", content: [{ type: "text", text: "And now?" }, { type: "image", source: {} }] }),
      message("user", 9, { role: "user", content: [
        { type: "text", text: "<ide_selection>The user selected lines 1 to 3 of a.ts</ide_selection>" },
        { type: "text", text: "Why is this slow?" },
      ] }),
      message("user", 10, { role: "user", content: "<div> does not render, why?" }),
      message("user", 11, { role: "user", content: "<bash-input>git status</bash-input>" }),
      message("user", 12, { role: "user", content: "<bash-stdout>On branch main</bash-stdout><bash-stderr></bash-stderr>" }),
      message("user", 13, { role: "user", content: [{ type: "image", source: {} }] }),
      message("user", 14, { role: "user", content: "<task-notification>A background command finished</task-notification>" }),
      message("user", 15, { role: "user", content: [{ type: "text", text: "<system-reminder>skills</system-reminder>" }] }),
    ]);
    expect(events.map(({ at, event }) => [at, event.type, "text" in event ? event.text : "message" in event ? event.message : null])).toEqual([
      [at(0), "notice", "Conversation compacted in Claude Code: what came before is in the summary the agent resumes from"],
      [at(1), "user_message", "Why does the build fail?"],
      [at(3), "assistant_text", "Let me look."],
      [at(3), "tool_call", null],
      [at(4), "tool_result", null],
      [at(5), "user_message", "/review the diff"],
      [at(8), "user_message", "And now?"],
      [at(9), "user_message", "Why is this slow?"],
      [at(10), "user_message", "<div> does not render, why?"],
      [at(11), "user_message", "!git status"],
      [at(13), "user_message", "(an image)"],
    ]);
    expect(events[1]!.event).toEqual({ type: "user_message", text: "Why does the build fail?", queued: false });
    expect(events[4]!.event).toMatchObject({ type: "tool_result", tool_use_id: "toolu_1" });
  });

  test("a session without a transcript is not found, and an id that is no file name is refused", async () => {
    const read = nothing;
    expect(await claudeSessionMessages(read, { agent: "claude", session_id: SESSION, cwd: "/w" })).toEqual({ found: false, events: [] });
    await expect(claudeSessionMessages(read, { agent: "claude", session_id: "../x", cwd: "/w" })).rejects.toThrow("not a session id");
  });

  test("is read with the SDK from the folder it is kept for, times included", async () => {
    const home = mkdtempSync(join(tmpdir(), "chauffeur-session-home-"));
    const cwd = realpathSync(mkdtempSync(join(tmpdir(), "chauffeur-session-cwd-")));
    try {
      const folder = join(home, "projects", cwd.replace(/[^a-zA-Z0-9]/g, "-"));
      mkdirSync(folder, { recursive: true });
      const row = (uuid: string, parentUuid: string | null, type: string, body: unknown, minute: number) =>
        JSON.stringify({ type, uuid, parentUuid, sessionId: SESSION, cwd, timestamp: at(minute), message: body });
      writeFileSync(join(folder, `${SESSION}.jsonl`), [
        row("m1", null, "user", { role: "user", content: "hi" }, 1),
        row("m2", "m1", "assistant", { id: "msg_1", role: "assistant", content: [{ type: "text", text: "hello" }] }, 2),
      ].join("\n") + "\n");
      const child = Bun.spawn(["bun", join(import.meta.dir, "support", "read-session.ts"), JSON.stringify({ agent: "claude", session_id: SESSION, cwd })], {
        env: { ...process.env, CLAUDE_CONFIG_DIR: home },
        stdout: "pipe",
        stderr: "pipe",
      });
      const out = await new Response(child.stdout).text();
      expect(await child.exited).toBe(0);
      expect(JSON.parse(out)).toEqual({ found: true, events: [
        { at: at(1), event: { type: "user_message", text: "hi", queued: false } },
        { at: at(2), event: { type: "assistant_text", text: "hello", message_id: "msg_1:0", parent_tool_use_id: null } },
      ] });
    } finally {
      rmSync(home, { recursive: true, force: true });
      rmSync(cwd, { recursive: true, force: true });
    }
  });
});
