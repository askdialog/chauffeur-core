// Writes the Jev plugin's files (plugins/jev, README aside) into a module the compiled sidecar
// carries; src/agents/claude/jev.ts writes them back to disk for Claude Code.
//
//   bun scripts/gen-jev-plugin.ts [--check]

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const root = join(dirname(import.meta.path), "..");
const pluginDir = join(root, "plugins/jev");
const out = join(root, "src/agents/claude/jev-plugin.generated.ts");

export function pluginFiles(dir = pluginDir): Record<string, string> {
  const files: Record<string, string> = {};
  const walk = (folder: string) => {
    for (const entry of readdirSync(folder, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const path = join(folder, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (relative(dir, path) !== "README.md") files[relative(dir, path)] = readFileSync(path, "utf8");
    }
  };
  walk(dir);
  return files;
}

export function generated(files = pluginFiles()): string {
  const entries = Object.entries(files).map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`);
  return [
    "// Generated by `bun scripts/gen-jev-plugin.ts` from plugins/jev: do not edit.",
    "",
    "export const JEV_PLUGIN_FILES: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const text = generated();
  if (Bun.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) {
      console.error(`${relative(root, out)} is stale: run bun scripts/gen-jev-plugin.ts`);
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.error(`wrote ${relative(root, out)}`);
  }
}
